import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

declare const Bun: {
  build(options: { entrypoints: string[]; target: "node"; format: "cjs"; minify: boolean }): Promise<{
    success: boolean; logs: unknown[]; outputs: Array<{ text(): Promise<string> }>;
  }>;
};
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const result = await Bun.build({ entrypoints: [resolve(root, "scripts/node-proxy-preload.cjs")], target: "node", format: "cjs", minify: true });
if (!result.success) throw new AggregateError(result.logs, "Node proxy preload build failed");
const license = await readFile(resolve(root, "node_modules/undici/LICENSE"), "utf8");
const fetchLicense = await readFile(resolve(root, "node_modules/undici/lib/web/fetch/LICENSE"), "utf8");
const source = `/* Undici (MIT)\n${license}\nUndici fetch (MIT)\n${fetchLicense}*/\n${await result.outputs[0]!.text()}`;
const generated = "// Generated by bun run build:node-proxy; source: scripts/node-proxy-preload.cjs.\n"
  + `export const NODE_PROXY_PRELOAD = ${JSON.stringify(source)};\n`;
const target = resolve(root, "zapsdk/execution/node-proxy-preload.generated.ts");
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== generated) throw new Error("Node proxy preload is stale; run bun run build:node-proxy");
} else {
  await writeFile(target, generated);
}
