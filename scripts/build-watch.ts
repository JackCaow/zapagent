import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

declare const Bun: {
  build(options: { entrypoints: string[]; target: "browser"; format: "iife"; minify: boolean }): Promise<{
    success: boolean; logs: unknown[]; outputs: Array<{ text(): Promise<string> }>;
  }>;
};
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
/** Embed all assets: compiled CLI and npm source entry work offline, without a CDN. */
export async function buildWatchHtml(): Promise<string> {
  const result = await Bun.build({ entrypoints: [resolve(root, "src/watch/client.ts")], target: "browser", format: "iife", minify: true });
  if (!result.success) throw new AggregateError(result.logs, "Watch client build failed");
  const [template, css, js, motionLicense, framerLicense, tslibLicense] = await Promise.all([
    readFile(resolve(root, "src/watch/client.template.html"), "utf8"),
    readFile(resolve(root, "src/watch/client.css"), "utf8"),
    result.outputs[0].text(),
    readFile(resolve(root, "node_modules/motion/LICENSE.md"), "utf8"),
    readFile(resolve(root, "node_modules/framer-motion/LICENSE.md"), "utf8"),
    readFile(resolve(root, "node_modules/tslib/LICENSE.txt"), "utf8"),
  ]);
  const licenses = `/* Motion / motion-dom / motion-utils\n${motionLicense}\nFramer Motion\n${framerLicense}\ntslib\n${tslibLicense}\n*/\n`;
  return "<!-- Generated by bun run build:watch. Edit client.ts, client.css, client.template.html. -->\n" + template
    .replace("/* WATCH_STYLES */", () => css)
    .replace("/* WATCH_SCRIPT */", () => (licenses + js).replaceAll("\r\n", "\n").replace(/<\/script/gi, "<\\/script"));
}
if (import.meta.main) {
  const html = await buildWatchHtml(), target = resolve(root, "src/watch/client.html");
  if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8") !== html) throw Error("Watch client.html is stale; run bun run build:watch");
    console.log("Watch embedded asset is current");
  } else { await writeFile(target, html); console.log(`Watch client embedded (${Math.round(Buffer.byteLength(html) / 1024)} KiB)`); }
}
